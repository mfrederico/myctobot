    /**
     * Generate pipeline API proxy routes
     */
    private function generatePipelineProxies(string $appDir, object $app): void {
        $pipelines = Bean::find('detachableapppipelines', 'detachableapps_id = ?', [$app->id]);

        foreach ($pipelines as $appPipeline) {
            $pipeline = Bean::load('pipelines', (int)$appPipeline->pipelines_id);
            if (!$pipeline->id) continue;

            $this->generatePipelineProxy($appDir, $pipeline);
        }
    }

