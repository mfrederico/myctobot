<?php
/**
 * ShopifyAppBuilder
 *
 * Builds proper Shopify apps from Detachable App configurations
 * using shopify-app-template-react-router and Shopify CLI.
 *
 * Architecture:
 * - Detachable App (screens, pipelines, liquid) → Shopify App
 * - MyCTOBot pipelines = Backend API
 * - Shopify CLI handles deployment
 */

namespace app\services;

use \Exception;
use \app\Bean;

class ShopifyAppBuilder {

    private const TEMPLATE_REPO = 'https://github.com/Shopify/shopify-app-template-react-router.git';

    private string $workspace;
    private string $buildDir;

    public function __construct(string $workspace = 'default') {
        $this->workspace = $workspace;
        $this->buildDir = "/tmp/{$workspace}/shopify-apps";
    }

    /**
     * Build a Shopify app from a Detachable App
     *
     * @param int $detachableAppId Detachable app ID
     * @return array Build result with app path, config, etc.
     */
    public function build(int $detachableAppId): array {
        $app = Bean::load('detachableapps', $detachableAppId);
        if (!$app->id) {
            throw new Exception("Detachable app #{$detachableAppId} not found");
        }

        $appName = $this->sanitizeAppName($app->name ?? 'MyCTOBot App');
        $appSlug = strtolower(preg_replace('/[^a-z0-9]+/i', '-', $appName));
        $appDir = $this->buildDir . '/' . $appSlug;

        // 1. Clone template
        $this->cloneTemplate($appDir);

        // 2. Generate shopify.app.toml with scopes
        $scopes = $this->collectScopes($app);
        $this->generateAppConfig($appDir, $appName, $scopes);

        // 3. Generate React routes from screens
        $this->generateScreenRoutes($appDir, $app);

        // 4. Generate pipeline API proxies
        $this->generatePipelineProxies($appDir, $app);

        // 5. Generate Liquid extensions from files
        $this->generateLiquidExtensions($appDir, $app);

        // 6. Generate package.json with backend URL
        $this->updatePackageConfig($appDir, $app);

        return [
            'success' => true,
            'app_dir' => $appDir,
            'app_name' => $appName,
            'app_slug' => $appSlug,
            'next_steps' => [
                "cd {$appDir}",
                "npm install",
                "shopify app deploy"
            ]
        ];
    }

    /**
     * Clone Shopify app template
     */
    private function cloneTemplate(string $appDir): void {
        if (file_exists($appDir)) {
            // Clean existing
            exec("rm -rf " . escapeshellarg($appDir));
        }

        @mkdir($this->buildDir, 0755, true);

        $cmd = sprintf(
            'git clone --depth 1 %s %s 2>&1',
            escapeshellarg(self::TEMPLATE_REPO),
            escapeshellarg($appDir)
        );

        exec($cmd, $output, $exitCode);

        if ($exitCode !== 0) {
            throw new Exception("Failed to clone template: " . implode("\n", $output));
        }

        // Remove .git directory
        exec("rm -rf " . escapeshellarg($appDir . '/.git'));
    }

    /**
     * Collect required Shopify scopes from app config
     */
    private function collectScopes(object $app): array {
        // Default scopes needed for theme apps
        $scopes = [
            'read_themes',
            'write_themes',
            'read_products',
            'read_content'
        ];

        // Add scopes from pipelines
        $pipelines = Bean::find('detachableapppipelines', 'detachableapps_id = ?', [$app->id]);
        foreach ($pipelines as $pipeline) {
            $pipelineBean = Bean::load('pipelines', (int)$pipeline->pipelines_id);
            if ($pipelineBean->id) {
                $steps = Bean::find('pipelinesteps', 'pipelines_id = ?', [$pipelineBean->id]);
                foreach ($steps as $step) {
                    $stepScopes = $this->getScopesForStepType($step->step_type);
                    $scopes = array_merge($scopes, $stepScopes);
                }
            }
        }

        return array_unique($scopes);
    }

    /**
     * Get required scopes for a pipeline step type
     */
    private function getScopesForStepType(string $stepType): array {
        $scopeMap = [
            'shopify_graphql' => ['read_products', 'read_orders', 'read_customers'],
            'email_out' => [],
            'webhook_out' => [],
            // Add more as needed
        ];

        return $scopeMap[$stepType] ?? [];
    }

    /**
     * Generate shopify.app.toml configuration
     */
    private function generateAppConfig(string $appDir, string $appName, array $scopes): void {
        // TOML format: scopes = "scope1, scope2, scope3"
        $scopesStr = implode(', ', $scopes);

        $config = <<<TOML
# Generated by MyCTOBot ShopifyAppBuilder
# NOTE: These are REQUESTED scopes. Actual approved scopes depend on store owner approval.
name = "{$appName}"
scopes = "{$scopesStr}"

[webhooks]
api_version = "2025-10"

  [[webhooks.subscriptions]]
  uri = "/webhooks/app/uninstalled"
  topics = ["app/uninstalled"]

TOML;

        file_put_contents($appDir . '/shopify.app.toml', $config);
    }

    /**
     * Generate React routes from Detachable App screens
     */
    private function generateScreenRoutes(string $appDir, object $app): void {
        $screens = Bean::find('detachableappscreens', 'detachableapps_id = ?', [$app->id]);

        $routes = [];
        foreach ($screens as $screen) {
            $routePath = $this->sanitizeRoutePath($screen->route_path ?? '/');
            $componentName = $this->sanitizeComponentName($screen->screen_name ?? 'Screen');

            // Generate React component
            $this->generateScreenComponent($appDir, $componentName, $screen);

            $routes[] = [
                'path' => $routePath,
                'component' => $componentName
            ];
        }

        // Generate app routing file
        $this->generateAppRoutes($appDir, $routes);
    }

