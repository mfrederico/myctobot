    /**
     * Generate Shopify theme extensions from Liquid files
     * NOTE: Shopify only allows ONE theme extension per app, so we create a single
     * extension with multiple blocks inside it.
     */
    private function generateLiquidExtensions(string $appDir, object $app): void {
        $liquidFiles = Bean::find('detachableappliquidfiles', 'detachableapps_id = ?', [$app->id]);

        // Filter out non-block files
        $blocks = [];
        foreach ($liquidFiles as $file) {
            $fileType = $file->file_type ?? 'app_block';
            // Skip asset files (JS/CSS)
            if (in_array($fileType, ['asset_js', 'asset_css', 'asset'])) {
                continue;
            }
            $blocks[] = $file;
        }

        if (empty($blocks)) {
            return;
        }

        // Create ONE theme extension with all blocks
        $appSlug = strtolower(preg_replace('/[^a-z0-9]+/i', '-', $app->name ?? 'app'));
        $extName = $appSlug . '-theme-blocks';
        $extDir = $appDir . '/extensions/' . $extName;

        @mkdir($extDir, 0755, true);

        // Create blocks directory
        $blocksDir = $extDir . '/blocks';
        @mkdir($blocksDir, 0755, true);

        // Create locales directory (required by Shopify CLI)
        $localesDir = $extDir . '/locales';
        @mkdir($localesDir, 0755, true);

        // Create default locale file
        $defaultLocale = [
            'name' => $app->name ?? 'MyCTOBot App',
            'description' => 'Theme blocks created by MyCTOBot'
        ];
        file_put_contents("{$localesDir}/en.default.json", json_encode($defaultLocale, JSON_PRETTY_PRINT));

        // Copy all Liquid blocks into the single extension
        foreach ($blocks as $file) {
            $fileName = $file->file_name ?? 'block.liquid';
            $content = $file->file_content ?? '';

            // Theme app extensions don't support {% script %} tag - convert to HTML <script>
            $content = str_replace(['{% script %}', '{% endscript %}'], ['<script>', '</script>'], $content);

            // Remove empty default values from schema (Shopify validation rejects "default": "")
            $content = preg_replace('/,?\s*"default"\s*:\s*""\s*,?/', '', $content);

            file_put_contents("{$blocksDir}/{$fileName}", $content);
        }

        // Generate extension config (no settings at extension level, blocks have their own)
        $config = [
            'type' => 'theme',
            'name' => $app->name ?? 'MyCTOBot App'
        ];

        file_put_contents("{$extDir}/shopify.extension.toml", $this->tomlEncode($config));
    }

    /**
     * Update package.json with MyCTOBot backend URL
     */
    private function updatePackageConfig(string $appDir, object $app): void {
        $packagePath = $appDir . '/package.json';
        $package = json_decode(file_get_contents($packagePath), true);

        // Add environment variable for backend URL
        $package['config'] = $package['config'] ?? [];
        $package['config']['MYCTOBOT_API_URL'] = 'https://dev.myctobot.ai';

        file_put_contents($packagePath, json_encode($package, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));
    }

    // Helper methods

    private function sanitizeAppName(string $name): string {
        return preg_replace('/[^a-zA-Z0-9\s-]/', '', $name);
    }

    private function sanitizeRoutePath(string $path): string {
        return '/' . trim($path, '/');
    }

    private function sanitizeComponentName(string $name): string {
        $name = preg_replace('/[^a-zA-Z0-9]/', '', ucwords($name));
        return ucfirst($name);
    }

    private function tomlEncode(array $data): string {
        // Simple TOML encoder for extension config
        $toml = '';
        foreach ($data as $key => $value) {
            if (is_string($value)) {
                $toml .= "{$key} = \"{$value}\"\n";
            } elseif (is_array($value)) {
                // Empty arrays should become empty objects in JSON to avoid TOML validation errors
                if (empty($value)) {
                    $toml .= "{$key} = {}\n";
                } else {
                    $toml .= "{$key} = " . json_encode($value) . "\n";
                }
            }
        }
        return $toml;
    }
